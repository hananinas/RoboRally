test('creating a lobby uses the selected map and can return to the lobby list', async ({ page, game }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Game options', exact: true }).click()
  const settings = page.getByRole('region', { name: 'Game options' })
  await expect(settings.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
  await expect(settings.getByRole('button', { name: 'Account Settings' })).toBeEnabled()
  await expect(settings.getByRole('button', { name: 'Leave game' })).toHaveCount(0)
  await expect(settings.getByText('Keybindings', { exact: true })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(settings).toBeHidden()

  await expect(page.getByRole('button', { name: 'Create lobby', exact: true })).toBeEnabled()
  await expect(page.getByRole('main', { name: 'Game board' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Create lobby', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Choose a map', exact: true })).toBeVisible()
  const emptyMap = page.getByRole('button', { name: 'Empty Map', exact: true })
  const testMap = page.getByRole('button', { name: 'Test Map', exact: true })
  await expect(emptyMap).toHaveAttribute('aria-pressed', 'true')
  await expect(testMap).toHaveAttribute('aria-pressed', 'false')
  await testMap.click()
  await expect(testMap).toHaveAttribute('aria-pressed', 'true')
  await expect(emptyMap).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByText('Selected map: Test Map', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Back to lobbies', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Create lobby', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Create lobby', exact: true }).click()
  await expect(page.getByText('Selected map: Empty Map', { exact: true })).toBeVisible()
  await testMap.click()
  await expect(page.getByText('Selected map: Test Map', { exact: true })).toBeVisible()
  await page.getByLabel('Lobby name').fill('Friday Night')
  await expect(page.getByRole('main', { name: 'Game board' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Create lobby', exact: true }).click()
  const mapPanel = page.getByRole('region', { name: 'Selected map' })
  await expect(mapPanel.getByText('Test Map', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Friday Night', exact: true })).toBeVisible()
  await expect(mapPanel.getByRole('img', { name: 'Test Map map preview' })).toHaveAttribute('src', /data:image\/svg\+xml;base64,/)
  const createRequest = (await game.snapshot()).entryRequests.find((request) => request.event === 'lobby.create')
  expect(createRequest).toMatchObject({ payload: { mapName: 'test-map', name: 'Friday Night' } })
  await page.getByRole('button', { name: 'Leave lobby', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Create lobby', exact: true })).toBeVisible()
})

test('joining requires selection and enters the waiting screen', async ({ page }) => {
  await page.goto('/')
  const join = page.getByRole('button', { name: 'Join game', exact: true })
  await expect(join).toBeDisabled()
  const row = page.getByRole('button', { name: /Lobby 1/ })
  await expect(row.getByText('1/6 players', { exact: true })).toBeVisible()
  await expect(row.getByRole('img', { name: 'Unlocked' })).toBeVisible()
  await expect(page.getByRole('list', { name: 'Lobbies' }).getByRole('listitem')).toHaveCount(1)
  await expect(row).toBeFocused()
  await row.click()
  await expect(row).toHaveAttribute('aria-pressed', 'true')
  await expect(join).toBeEnabled()
  await join.click()
  await expect(page.getByRole('button', { name: 'Leave lobby', exact: true })).toBeEnabled()
  const mapPanel = page.getByRole('region', { name: 'Selected map' })
  const robotPanel = page.getByRole('complementary', { name: 'Your robot' })
  await expect(mapPanel.getByRole('img', { name: 'Test Map map preview' })).toBeVisible()
  for (const width of [1280, 375]) {
    await page.setViewportSize({ width, height: 800 })
    const [map, robot] = await Promise.all([mapPanel.boundingBox(), robotPanel.boundingBox()])
    if (!map || !robot) throw new Error('Lobby panel positions are unavailable')
    expect(map.x).toBeCloseTo(robot.x)
    expect(map.width).toBeCloseTo(robot.width)
    expect(map.y + map.height).toBeLessThan(robot.y)
  }
  await expect(page.getByRole('main', { name: 'Game board' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Leave lobby', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Create lobby', exact: true })).toBeEnabled()
})

test('selects a robot in the waiting lobby', async ({ page }) => {
  await page.goto('/')
  await createLobby(page)

  const picker = page.getByRole('group', { name: 'Choose a robot' })
  const robotPanel = page.getByRole('complementary', { name: 'Your robot' })
  const mapTop = await page.getByRole('region', { name: 'Selected map' })
    .evaluate((element) => element.getBoundingClientRect().top)
  const robotTop = await robotPanel.evaluate((element) => element.getBoundingClientRect().top)
  expect(mapTop).toBeLessThan(robotTop)
  const choices = picker.getByRole('button', { name: /^Robot option \d+$/ })
  await expect(choices).toHaveCount(6)
  await expect(robotPanel.getByRole('heading', { name: 'Tank', exact: true })).toBeVisible()
  await expect(choices.nth(0)).toHaveAttribute('aria-pressed', 'true')
  await expect(choices.nth(0).locator('.robot-preview__layer')).toHaveCount(8)
  for (let index = 0; index < 6; index += 1) {
    await expect(choices.nth(index).locator('.robot-preview__layer').first()).toBeVisible()
  }
  const tankPortrait = page.getByRole('list', { name: 'Lobby seats' })
    .getByLabel('Tank robot').locator('.robot-preview')
  const tankPortraitBox = await tankPortrait.boundingBox()
  expect(tankPortraitBox?.width).toBe(28)
  await expect(tankPortrait.locator('.robot-preview__layer').first()).toHaveAttribute('viewBox', '0 0 57 87')
  await expect(page.getByText('Player colour', { exact: true })).toBeVisible()
  const colorButtons = page.getByRole('button', { name: /^(Blue|Red|Yellow|Green|Purple|Pink)$/ })
  await expect(colorButtons).toHaveCount(6)
  await expect(colorButtons.nth(0)).toHaveAttribute('aria-pressed', 'true')
  await expect(colorButtons.nth(0)).toBeEnabled()

  await choices.nth(1).click()
  await expect(robotPanel.getByRole('heading', { name: 'Scout', exact: true })).toBeVisible()
  const playerSprite = page.getByRole('list', { name: 'Lobby seats' })
    .getByLabel('Scout robot').locator('.robot-preview__layer')
  await expect(playerSprite).toBeVisible()
  await expect(playerSprite).toHaveAttribute('viewBox', '0 0 100 100')
  await expect(choices.nth(0)).toHaveAttribute('aria-pressed', 'false')
  await expect(choices.nth(1)).toHaveAttribute('aria-pressed', 'true')
  const stage = page.getByRole('complementary', { name: 'Your robot' }).locator('.robot-picker__stage')
  const stageSprite = stage.locator('.robot-preview__layer')
  await expect(stageSprite).toHaveAttribute('viewBox', '0 0 100 100')

  await choices.nth(0).click()
  await expect(robotPanel.getByRole('heading', { name: 'Tank', exact: true })).toBeVisible()
  await expect(choices.nth(0)).toHaveAttribute('aria-pressed', 'true')
  await expect(stageSprite.first()).toHaveAttribute('viewBox', '0 0 57 87')
  await expect(tankPortrait.locator('.robot-preview__layer').first()).toHaveAttribute('viewBox', '0 0 57 87')
})

